#!/usr/bin/env python3
"""Write docs/_generated/GATES.md: measured wall time per ./run.sh arm and gate facts.

This is the `report` arm of ./run.sh. Every number in the generated document is
produced here - arm commands come from `./run.sh --list`, wall times from one
timed run per arm on this host, and the GNN pin from .github/gnn-pin.json. Do
not hand-edit the document; run `./run.sh report` instead.

Run:  ./run.sh report   (or: python3 scripts/gate_report.py)
"""

from __future__ import annotations

import datetime
import json
import platform
import re
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PIN_PATH = ROOT / ".github" / "gnn-pin.json"
TARGET = ROOT / "docs" / "_generated" / "GATES.md"
SKIP = {"report"}
VFE_SUMMARY_RE = re.compile(r"^Variational Free Energy Simulator\s*\|\s*(\d+)\s+(\d+)", re.MULTILINE)


def arms() -> list[tuple[str, str]]:
    listing = subprocess.run(["./run.sh", "--list"], cwd=ROOT, check=True, capture_output=True, text=True)
    return [
        tuple(line.split("\t", 1))
        for line in listing.stdout.splitlines()
        if "\t" in line
    ]


def measure(arm: str) -> tuple[float, int, str]:
    started = time.monotonic()
    completed = subprocess.run(["./run.sh", arm], cwd=ROOT, capture_output=True, text=True)
    elapsed = time.monotonic() - started
    return elapsed, completed.returncode, completed.stdout + completed.stderr


def main() -> int:
    rows: list[tuple[str, str, float, int]] = []
    outputs: dict[str, str] = {}
    for name, command in arms():
        if name in SKIP:
            continue
        elapsed, code, output = measure(name)
        rows.append((name, command, elapsed, code))
        outputs[name] = output
        status = "pass" if code == 0 else f"FAIL ({code})"
        print(f"{name:<10} {elapsed:7.2f}s  {status}", file=sys.stderr)

    pin = json.loads(PIN_PATH.read_text(encoding="utf-8"))
    plaintext_files = sorted((ROOT / "TextbookContent" / "PlainText").glob("*.txt"))
    assertions = VFE_SUMMARY_RE.search(outputs.get("vfe", ""))

    lines = [
        "<!-- generated by scripts/gate_report.py via `./run.sh report`; do not edit -->",
        "",
        "# Gate measurements",
        "",
        f"Generated {datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%d %H:%M UTC')} on "
        f"`{platform.platform()}` with Python {platform.python_version()}. One timed run per arm, "
        "wall clock, no warm-up: a local observation on the host that produced this file, not a "
        "performance claim and not a substitute for a green run.",
        "",
        "| Arm | Exact command | Wall time (s) | Result |",
        "| --- | --- | --- | --- |",
    ]
    for name, command, elapsed, code in rows:
        status = "pass" if code == 0 else f"failed ({code})"
        lines.append(f"| `{name}` | `{command}` | {elapsed:.2f} | {status} |")

    lines += [
        "",
        "## Facts",
        "",
        "| Fact | Value | Source |",
        "| --- | --- | --- |",
        f"| Plaintext files | {len(plaintext_files)} | `TextbookContent/PlainText/*.txt` |",
        f"| VFE assertions | {assertions.group(2) if assertions else 'not parsed'} | `./run.sh vfe` test summary |",
        f"| GNN pin schema | `{pin['schema']}` | `.github/gnn-pin.json` |",
        f"| GNN pin tag | `{pin['tag']}` | `.github/gnn-pin.json` |",
        f"| GNN pin revision | `{pin['revision']}` | `.github/gnn-pin.json` |",
        "",
        "The `report` arm itself is excluded from the table; it is the arm that writes this file.",
        "",
    ]
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text("\n".join(lines), encoding="utf-8")
    print(f"gate report: wrote {TARGET.relative_to(ROOT)}", file=sys.stderr)
    return 1 if any(code != 0 for _, _, _, code in rows) else 0


if __name__ == "__main__":
    sys.exit(main())
